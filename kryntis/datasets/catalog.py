# Helper functions — Datasets
# ════════════════════════════════════════════════════════════════════════════════

def get_catalog_by_domain(domain: str) -> list[DatasetSource]:
    """Return all datasets belonging to a specific domain."""
    return [ds for ds in DATASET_CATALOG if ds.domain == domain]


def get_all_domains() -> list[str]:
    """Return unique domain names in catalog order."""
    return list(dict.fromkeys(ds.domain for ds in DATASET_CATALOG))


def get_catalog_by_phase(phase: int = 1) -> list[DatasetSource]:
    """Return all datasets whose phase is <= the given phase."""
    return [ds for ds in DATASET_CATALOG if ds.phase <= phase]


def get_catalog_by_source_type(source_type: str) -> list[DatasetSource]:
    """Return datasets filtered by source_type ('synthetic' or 'github')."""
    return [ds for ds in DATASET_CATALOG if ds.source_type == source_type]


# ════════════════════════════════════════════════════════════════════════════════
# Helper functions — Models
# ════════════════════════════════════════════════════════════════════════════════

def get_all_models() -> list[ModelSource]:
    """Return all model sources."""
    return MODEL_CATALOG


def get_trainable_profiles() -> list[ModelSource]:
    """Return serving profiles with custom Kryntis training-domain hints."""
    return MODEL_CATALOG


def get_models_by_domain(domain: str) -> list[ModelSource]:
    """Return models recommended for a given training domain."""
    return [m for m in MODEL_CATALOG if domain in m.recommended_domains]


def get_model_by_id(model_id: str) -> ModelSource | None:
    """Look up a model by its id."""
    return next((m for m in MODEL_CATALOG if m.id == model_id), None)


def get_models_under_size(max_gb: float) -> list[ModelSource]:
    """Return models whose download size is at or below max_gb."""
    return [m for m in MODEL_CATALOG if m.size_gb <= max_gb]
